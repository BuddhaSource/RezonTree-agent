// EIP-712 §"Definition of encodeType":
//   1. Encode primary type as `Name(type1 field1,type2 field2,...)`.
//   2. Append every referenced struct type, sorted alphabetically by
//      name. A reference is any field whose base type (after stripping
//      `[]`) appears as a key in the types map.
//   3. The final string is keccak'd to produce the typehash.
//
// Reproducing this here (rather than calling viem's internal helper)
// is intentional — the test must NOT use the same code path the
// production sign uses, otherwise a bug in the encoder hides the
// drift it's trying to catch.
function encodeType(
  primary: string,
  types: Record<
    string,
    readonly { readonly name: string; readonly type: string }[]
  >,
): string {
  const visit = (name: string): string => {
    const fields = types[name];
    if (!fields) {
      throw new Error(`encodeType: unknown type "${name}"`);
    }
    const args = fields.map((f) => `${f.type} ${f.name}`).join(",");
    return `${name}(${args})`;
  };

  // Walk references transitively, gathering every struct that
  // appears reachable from `primary`. Excludes `primary` itself.
  const referenced = new Set<string>();
  const queue: string[] = [primary];
  while (queue.length > 0) {
    const cur = queue.shift()!;
    const fields = types[cur];
    if (!fields) continue;
    for (const f of fields) {
      const baseType = f.type.replace(/\[\]$/, "");
      if (baseType !== cur && types[baseType] && !referenced.has(baseType)) {
        referenced.add(baseType);
        queue.push(baseType);
      }
    }
  }

  const refsSorted = [...referenced].sort();
  return visit(primary) + refsSorted.map(visit).join("");
}

function typehashOf(
  primary: string,
  types: Record<
    string,
    readonly { readonly name: string; readonly type: string }[]
  >,
): string {
  return keccak256(stringToBytes(encodeType(primary, types)));
}

describe("EIP-712 typehash — derived from runtime type arrays", () => {
  // Each test hashes the LIVE typed-data array the SDK uses to sign.
  // A field rename, type change, or reorder in *-intent.ts flips the
  // hash and the test fails. The test is BEFORE the round-trip path —
  // catches drift at unit-test time, never lets a malformed intent
  // reach a chain.

  it("SponsorIntent", () => {
    const computed = typehashOf("SponsorIntent", SPONSOR_INTENT_TYPES);
    expect(computed).toBe(PINNED.SponsorIntent);
  });

  it("CosponsorIntent", () => {
    const computed = typehashOf("CosponsorIntent", COSPONSOR_INTENT_TYPES);
    expect(computed).toBe(PINNED.CosponsorIntent);
  });

  it("CommitIntent", () => {
    const computed = typehashOf("CommitIntent", COMMIT_INTENT_TYPES);
    expect(computed).toBe(PINNED.CommitIntent);
  });

  it("VoteIntent", () => {
    const computed = typehashOf("VoteIntent", VOTE_INTENT_TYPES);
    expect(computed).toBe(PINNED.VoteIntent);
  });

  it("SettlementIntent", () => {
    const computed = typehashOf("SettlementIntent", SETTLEMENT_INTENT_TYPES);
    expect(computed).toBe(PINNED.SettlementIntent);
  });
});

// Self-test — the encoder is non-trivial enough to deserve its own
// fence. Without this, an encoder bug could silently produce the
// same wrong hash from multiple drifting type arrays.
describe("encodeType — self-test", () => {
  it("primary with no references", () => {
    const types = {
      Foo: [
        { name: "a", type: "uint256" },
        { name: "b", type: "address" },
      ],
    } as const;
    expect(encodeType("Foo", types)).toBe("Foo(uint256 a,address b)");
  });

  it("primary with one referenced struct (alphabetized after primary)", () => {
    const types = {
      Order: [
        { name: "user", type: "address" },
        { name: "item", type: "Item" },
      ],
      Item: [
        { name: "sku", type: "uint256" },
        { name: "qty", type: "uint256" },
      ],
    } as const;
    expect(encodeType("Order", types)).toBe(
      "Order(address user,Item item)Item(uint256 sku,uint256 qty)",
    );
  });

  it("primary with array reference (`[]` stripped before lookup)", () => {
    const types = {
      Cart: [{ name: "items", type: "Item[]" }],
      Item: [{ name: "sku", type: "uint256" }],
    } as const;
    expect(encodeType("Cart", types)).toBe(
      "Cart(Item[] items)Item(uint256 sku)",
    );
  });

  it("references sorted alphabetically (B before C even if listed C-first)", () => {
    const types = {
      A: [
        { name: "c", type: "C" },
        { name: "b", type: "B" },
      ],
      C: [{ name: "x", type: "uint256" }],
      B: [{ name: "y", type: "uint256" }],
    } as const;
    expect(encodeType("A", types)).toBe(
      "A(C c,B b)B(uint256 y)C(uint256 x)",
    );
  });

  it("throws on unknown referenced type", () => {
    const types = { Foo: [{ name: "x", type: "uint256" }] } as const;
    expect(() => encodeType("Bar", types)).toThrow(/unknown type/);
  });
});

