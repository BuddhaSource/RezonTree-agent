// Field-shape contract — pinned arity + ordering for each intent
// type. A drift in the array length or first-field type tells you
// IMMEDIATELY which intent regressed, separately from the typehash
// hex assertion (which only tells you "something changed somewhere").
describe("EIP-712 type arrays — arity + first-field shape", () => {
  type FieldList = readonly { readonly name: string; readonly type: string }[];
  const cases: { name: string; fields: FieldList; arity: number; first: { name: string; type: string } }[] = [
    {
      name: "SponsorIntent",
      fields: SPONSOR_INTENT_TYPES.SponsorIntent,
      arity: 19,
      first: { name: "questionId", type: "bytes32" },
    },
    {
      name: "CosponsorIntent",
      fields: COSPONSOR_INTENT_TYPES.CosponsorIntent,
      arity: 7,
      first: { name: "questionId", type: "bytes32" },
    },
    {
      name: "CommitIntent",
      fields: COMMIT_INTENT_TYPES.CommitIntent,
      arity: 9,
      first: { name: "questionId", type: "bytes32" },
    },
    {
      name: "VoteIntent",
      fields: VOTE_INTENT_TYPES.VoteIntent,
      arity: 9,
      first: { name: "questionId", type: "bytes32" },
    },
    {
      name: "SettlementIntent",
      fields: SETTLEMENT_INTENT_TYPES.SettlementIntent,
      arity: 9,
      first: { name: "questionId", type: "bytes32" },
    },
  ];

  for (const c of cases) {
    it(`${c.name} has exactly ${c.arity} fields, first is {${c.first.name}: ${c.first.type}}`, () => {
      expect(c.fields.length).toBe(c.arity);
      expect(c.fields[0]).toEqual(c.first);
    });
  }
});
