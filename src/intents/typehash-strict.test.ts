// typehash-strict.test.ts — derives EIP-712 typehashes FROM the actual
// viem type arrays the SDK signs against, then asserts they match the
// hex pinned in the on-chain RezonForge.sol source.
//
// Why this is stricter than typehash.test.ts: that test hashes a
// hand-maintained `TYPEHASH_STRINGS` constant. Drift between the
// constant and the runtime EIP-712 type array (e.g. someone adds a
// field to SPONSOR_INTENT_TYPES but forgets the string) goes
// undetected. This test computes the typehash string from
// SPONSOR_INTENT_TYPES at test time, so any mutation to the live
// type definition — added field, renamed field, reordered field,
// type changed, FeeShare reference removed — flips the keccak hash
// and the test fails loudly with the chain-side hash unchanged.
//
// Lifecycle coverage:
//
//   Solidity typehash literal  →  pinned hex (PINNED below)
//   ──────────────────────────────────────────────────────────
//   Go signer typehash strings →  internal/signer/*.go (peer test
//                                  in the Go suite)
//   TS  typed-data arrays      →  src/intents/*-intent.ts
//                                  (THIS test recomputes from the
//                                   array and asserts == PINNED)
//   UI  typed-data arrays      →  RezonTree-UI/lib/intents/*.ts
//                                  (peer test in UI suite)
//
// Any one of those four layers drifting from the rest will change the
// computed hash. The chain rejects the resulting signature with
// ForgeBadSigner — an opaque revert deep in the broadcast path. This
// test surfaces the drift class instantly, before code reaches a chain.
//
// Update protocol: when a typehash changes, update ALL FOUR layers in
// the same PR. Never one without the others.

